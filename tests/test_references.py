class TestTargetSizeValidation:
    """F10: normalize()'s docstring documents a ValueError for a malformed
    target_size (not a pair of positive integers), but the optional-
    parameter change (target_size: tuple[int, int] | None = None) made
    this a two-branch path -- `target_size is None` skips validation
    entirely, `target_size is not None` validates it -- and neither branch
    had a test."""

    @pytest.mark.parametrize(
        "malformed_target_size",
        [
            (0, 64),  # zero width
            (64, -1),  # negative height
            (64,),  # wrong arity: unpacking itself raises ValueError
        ],
    )
    def test_malformed_target_size_raises_value_error(self, malformed_target_size):
        with pytest.raises(ValueError):
            normalize(FIXTURES_DIR / "valid_landscape.jpg", target_size=malformed_target_size)

    def test_none_target_size_bypasses_validation_entirely(self):
        """The `target_size is None` branch must reach neither the
        unpacking nor the positivity check -- confirmed by the fact that
        None itself would fail both if it were run through them."""
        result = normalize(FIXTURES_DIR / "valid_landscape.jpg", target_size=None)
        assert isinstance(result, NormalizedReference)


class TestSourcePreservation:
    """spec.md sec 6.1: references are opened read-only; normalize() must
    never write to, rename, or relocate the source file."""

    def test_source_file_untouched_after_normalize(self, tmp_path: Path):
        source = tmp_path / "source.png"
        shutil.copy(FIXTURES_DIR / "valid_portrait.png", source)
        original_bytes = source.read_bytes()
        original_mtime = source.stat().st_mtime_ns

