def test_neutral_fill_value_pinned_to_documented_constant():
    """Every fill-color assertion in this file derives `_FILL_RGB` from the
    imported `NEUTRAL_FILL_VALUE`, so changing the constant to any other
    value would still pass the whole suite -- this is the one assertion
    that pins the constant itself, rather than re-deriving from it. 128 does
    not yet appear in any user-facing doc (AC-DOC-1); closing that gap is
    S13's responsibility, not this story's -- this test only guards against
    the constant silently drifting away from what S13 will eventually
    document."""
    assert NEUTRAL_FILL_VALUE == 128


def _content_bounding_box(image: Image.Image, *, tolerance: int = 8) -> tuple[int, int, int, int]:
    """Return (min_x, min_y, max_x, max_y) of pixels that differ from the
    neutral fill color by more than `tolerance` on any channel.

    Used to measure the actual pasted content region on a padded canvas
    without relying on the implementation's own internal math -- a per-axis
    independent stretch bug (forbidden by AC-PROCESS-1/2) would leave NO
    fill-colored border on the axis it wrongly stretched, which this
    bounding box directly reveals.
    """
    pixels = image.load()
    width, height = image.size
    min_x, min_y, max_x, max_y = width, height, -1, -1
    for y in range(height):
        for x in range(width):
            r, g, b = pixels[x, y][:3]
            if (
                abs(r - _FILL_RGB[0]) > tolerance
                or abs(g - _FILL_RGB[1]) > tolerance
                or abs(b - _FILL_RGB[2]) > tolerance
            ):
                min_x, min_y = min(min_x, x), min(min_y, y)
                max_x, max_y = max(max_x, x), max(max_y, y)
    assert max_x >= 0, "no non-fill content found on canvas"
    return min_x, min_y, max_x, max_y


