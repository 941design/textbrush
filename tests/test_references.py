class TestFailureTaxonomy:
    """AC-INPUT-3: each failure class uses a real fixture exhibiting that
    exact failure mode, not a mocked open() call (VQ-S3-009)."""

    def test_unsupported_extension_real_decodable_file_rejected_by_extension(self):
        """unsupported_extension.bmp is a real, decodable image -- it must
        be rejected purely on its extension, proving the check is
        extension-based and not merely 'decode failed'."""
        path = FIXTURES_DIR / "unsupported_extension.bmp"
        assert path.exists()
        # Sanity: PIL itself can decode this file -- if normalize() rejects
        # it, that must be the extension check, not an incidental decode error.
        with Image.open(path) as img:
            img.load()

        with pytest.raises(UnsupportedExtensionError, match=r"\.bmp"):
            normalize(path, target_size=(64, 64))

    def test_missing_file_raises_reference_not_found(self, tmp_path: Path):
        missing = tmp_path / "does_not_exist.png"
        assert not missing.exists()

        with pytest.raises(ReferenceNotFoundError):
            normalize(missing, target_size=(64, 64))

    def test_unreadable_file_raises_unreadable_reference_error(self, tmp_path: Path):
        if os.name != "posix":
            pytest.skip("permission-bit test requires a POSIX filesystem")
        if hasattr(os, "getuid") and os.getuid() == 0:
            pytest.skip("root bypasses permission bits; cannot exercise this failure as root")

        source = FIXTURES_DIR / "valid_landscape.jpg"
        unreadable = tmp_path / "unreadable.jpg"
        shutil.copy(source, unreadable)
        unreadable.chmod(0o000)
        try:
            with pytest.raises(UnreadableReferenceError):
                normalize(unreadable, target_size=(64, 64))
        finally:
            unreadable.chmod(0o644)

    @pytest.mark.parametrize(
        "fixture_name",
        ["corrupt_truncated.jpg", "corrupt_not_an_image.png", "corrupt_empty.jpg"],
    )
    def test_corrupt_files_raise_corrupt_reference_error(self, fixture_name: str):
        path = FIXTURES_DIR / fixture_name
        assert path.exists()

        with pytest.raises(CorruptReferenceError):
            normalize(path, target_size=(64, 64))

    def test_decode_resource_constrained_raises_actionable_error(self, monkeypatch):
        """Lowers Pillow's real decompression-bomb guard (MAX_IMAGE_PIXELS)
        below the fixture's actual pixel count and confirms the REAL
        decoder's real safety mechanism fires -- not a simulated failure --
        satisfying VQ-S3-001's 'verified independently of the test harness'
        for this failure class without committing a multi-hundred-megapixel
        fixture to the repository."""
        path = FIXTURES_DIR / "valid_square.png"  # 400x400 = 160,000 pixels
        monkeypatch.setattr(Image, "MAX_IMAGE_PIXELS", 100)

        with pytest.raises(ReferenceResourceConstrainedError):
            normalize(path, target_size=(64, 64))

    def test_decompression_bomb_warning_tier_also_raises_resource_constrained_error(
        self, monkeypatch
    ):
        """F4: Pillow's decompression-bomb guard has two tiers gated on
        MAX_IMAGE_PIXELS -- above 2x it raises DecompressionBombError
        (covered by the test above), but between 1x and 2x it only emits a
        DecompressionBombWarning and, by default, proceeds to decode
        anyway. At the ratio used here (400x400 = 160,000 pixels against a
        100,000-pixel ceiling, exactly 1.6x) only the warning tier fires;
        without _decode()'s warnings-as-errors promotion this call would
        silently succeed, and under a warnings-as-errors interpreter
        setting it would instead raise a bare DecompressionBombWarning
        outside the ReferenceImageError hierarchy -- which S7's
        acknowledgement-time handler (AC-STATE-3, AC-RECOVERY-1) would not
        catch."""
        path = FIXTURES_DIR / "valid_square.png"  # 400x400 = 160,000 pixels
        monkeypatch.setattr(Image, "MAX_IMAGE_PIXELS", 100_000)  # 1.6x ratio

        with pytest.raises(ReferenceResourceConstrainedError):
            normalize(path, target_size=(64, 64))

    def test_decompression_bomb_warning_tier_raises_under_host_warnings_as_errors(
        self, monkeypatch
    ):
        """Round 3 finding C2: round 2 (N3) correctly removed the
        thread-unsafe global-filter mutation from production code, but in
        doing so also dropped `DecompressionBombWarning` from `_decode`'s
        `except` clause -- reopening the original gap in a narrower form.
        When the HOST APPLICATION (not this module) has independently
        configured `warnings.simplefilter("error",
        Image.DecompressionBombWarning)`, `Image.open()` raises the
        warning as an exception from INSIDE itself, before `_decode`'s
        header-size check ever runs -- so without the restored `except`
        clause this would escape as a bare `DecompressionBombWarning`
        outside the `ReferenceImageError` hierarchy, uncatchable by S7's
        acknowledgement-time handler (AC-STATE-3, AC-RECOVERY-1). The
        warnings-as-errors filter here is configured by THIS TEST, scoped
        to the `with` block via `catch_warnings()`, never by production
        code -- exercising exactly the host configuration this finding is
        about, distinct from round 2's test above which covers only the
        default (non-warnings-as-errors) case."""
        path = FIXTURES_DIR / "valid_square.png"  # 400x400 = 160,000 pixels
        monkeypatch.setattr(Image, "MAX_IMAGE_PIXELS", 100_000)  # 1.6x ratio

        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with pytest.raises(ReferenceResourceConstrainedError):
                normalize(path, target_size=(64, 64))

    def test_resource_constrained_failure_does_not_return_degraded_result(self, monkeypatch):
        """A resource failure must raise, never silently return a cropped,
        stretched, or substituted NormalizedReference (spec.md sec 6.2)."""
        path = FIXTURES_DIR / "valid_square.png"
        monkeypatch.setattr(Image, "MAX_IMAGE_PIXELS", 100)

        result = None
        try:
            result = normalize(path, target_size=(64, 64))
        except ReferenceResourceConstrainedError:
            pass
        assert result is None

    def test_normalization_stage_failure_raises_normalization_error(self, monkeypatch):
        """A failure during scale/pad (as opposed to decode) is reported as
        NormalizationError, distinct from the decode-time taxonomy."""
        monkeypatch.setattr(
            normalize_module,
            "_scale_and_pad",
            lambda *args, **kwargs: (_ for _ in ()).throw(MemoryError()),
        )

        with pytest.raises(NormalizationError):
            normalize(FIXTURES_DIR / "valid_landscape.jpg", target_size=(64, 64))

    def test_all_taxonomy_errors_share_reference_image_error_base(self):
        for cls in (
            UnsupportedExtensionError,
            ReferenceNotFoundError,
            UnreadableReferenceError,
            CorruptReferenceError,
            ReferenceResourceConstrainedError,
            NormalizationError,
        ):
            assert issubclass(cls, ReferenceImageError)


